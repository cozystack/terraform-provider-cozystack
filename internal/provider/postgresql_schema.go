func pgUsersResourceAttribute() rschema.MapNestedAttribute {
	return rschema.MapNestedAttribute{
		Optional:            true,
		MarkdownDescription: "PostgreSQL users keyed by user name.",
		NestedObject: rschema.NestedAttributeObject{
			Attributes: map[string]rschema.Attribute{
				"password": rschema.StringAttribute{
					Optional: true, Computed: true, Sensitive: true,
					MarkdownDescription: "Password for the user (autogenerated when omitted).",
				},
				"replication": rschema.BoolAttribute{
					Optional: true, Computed: true,
					Default:             booldefault.StaticBool(false),
					MarkdownDescription: "Whether the user has replication privileges.",
				},
			},
		},
	}
}

func pgDatabasesResourceAttribute() rschema.MapNestedAttribute {
	return rschema.MapNestedAttribute{
		Optional:            true,
		MarkdownDescription: "Databases keyed by name.",
		NestedObject: rschema.NestedAttributeObject{
			Attributes: map[string]rschema.Attribute{
				"extensions": rschema.ListAttribute{
					Optional: true, ElementType: types.StringType,
					MarkdownDescription: "Enabled PostgreSQL extensions.",
				},
				"roles": rschema.SingleNestedAttribute{
					Optional:            true,
					MarkdownDescription: "User roles for this database.",
					Attributes: map[string]rschema.Attribute{
						"admin":    rschema.ListAttribute{Optional: true, ElementType: types.StringType, MarkdownDescription: "Users with admin privileges."},
						"readonly": rschema.ListAttribute{Optional: true, ElementType: types.StringType, MarkdownDescription: "Users with read-only privileges."},
					},
				},
			},
		},
	}
}

func postgresSchema() rschema.Schema {
	attributes := identityResourceAttributes("Postgres instance name (`metadata.name`). Immutable.")

	maps.Copy(attributes, map[string]rschema.Attribute{
		attrReplicas: rschema.Int64Attribute{
			Optional: true, Computed: true,
			Default:             int64default.StaticInt64(2),
			MarkdownDescription: "Number of PostgreSQL replicas.",
		},
		attrResources:       resourcesResourceAttribute(),
		attrResourcesPreset: presetAttribute("t1.micro"),
		attrSize: rschema.StringAttribute{
			Optional: true, Computed: true,
			Default:             stringdefault.StaticString("10Gi"),
			MarkdownDescription: "Persistent volume size (quantity, e.g. `10Gi`).",
		},
		attrStorageClass: storageClassAttribute(),
		attrExternal:     externalAttribute(),
		specTLS: tlsResourceAttribute(
			"TLS configuration. This only controls whether the external hostname is added to the " +
				"operator-managed server certificate; CNPG keeps TLS on the wire either way, and turning " +
				"PostgreSQL TLS off entirely is a server-parameter matter. Omit the block to follow `external`.",
		),
		specBackup: backupResourceAttribute(
			"Backup configuration. Only the system-bucket opt-in is managed here — the per-release S3 " +
				"settings are deprecated upstream in favour of the platform-managed backup class and are " +
				"deliberately left unmanaged. Omitting the block leaves the flag to the server; once an " +
				"instance has opted in, set `use_system_bucket = false` to opt back out, because deleting " +
				"the block keeps the last applied value. Like every unmanaged part of the spec, backup " +
				"fields set outside Terraform are not carried over by an apply.",
		),
		attrVersion: rschema.StringAttribute{
			Optional: true, Computed: true,
			Default:             stringdefault.StaticString("v18"),
			Validators:          []validator.String{stringvalidator.OneOf("v18", "v17", "v16", "v15", "v14", "v13")},
			MarkdownDescription: "PostgreSQL major version (`v18`…`v13`).",
		},
		"users":     pgUsersResourceAttribute(),
		"databases": pgDatabasesResourceAttribute(),
		"endpoints": rschema.SingleNestedAttribute{
			Computed: true,
			MarkdownDescription: "Connection endpoints (from the CNPG `<name>-rw`/`<name>-ro` Services). " +
				"Populated once the instance is ready.",
			Attributes: map[string]rschema.Attribute{
				"host":      rschema.StringAttribute{Computed: true, MarkdownDescription: "Primary (read-write) service host."},
				"read_host": rschema.StringAttribute{Computed: true, MarkdownDescription: "Replica (read-only) service host."},
				"port":      rschema.Int64Attribute{Computed: true, MarkdownDescription: "PostgreSQL port."},
			},
		},
	})
	maps.Copy(attributes, statusResourceAttributes())
	maps.Copy(attributes, waitBehaviorAttributes())

	return rschema.Schema{
		MarkdownDescription: "A Cozystack managed PostgreSQL instance, deployed inside a tenant namespace. " +
			"The postgresql tuning, quorum, and bootstrap blocks use server defaults.",
		Attributes: attributes,
	}
}

func postgresDataSourceSchema() dsschema.Schema {
	attributes := identityDataSourceAttributes("Postgres instance name.")

	rolesDS := dsschema.SingleNestedAttribute{
		Computed:            true,
		MarkdownDescription: "User roles for this database.",
		Attributes: map[string]dsschema.Attribute{
			"admin":    dsschema.ListAttribute{Computed: true, ElementType: types.StringType, MarkdownDescription: "Admin users."},
			"readonly": dsschema.ListAttribute{Computed: true, ElementType: types.StringType, MarkdownDescription: "Read-only users."},
		},
	}

	maps.Copy(attributes, map[string]dsschema.Attribute{
		attrReplicas:        dsschema.Int64Attribute{Computed: true, MarkdownDescription: "Number of replicas."},
		attrResources:       resourcesDataSourceAttribute(),
		attrResourcesPreset: dsschema.StringAttribute{Computed: true, MarkdownDescription: "Sizing preset."},
		attrSize:            dsschema.StringAttribute{Computed: true, MarkdownDescription: "Persistent volume size."},
		attrStorageClass:    dsschema.StringAttribute{Computed: true, MarkdownDescription: "StorageClass used to store the data."},
		attrExternal:        dsschema.BoolAttribute{Computed: true, MarkdownDescription: "Whether external access is enabled."},
		specTLS:             tlsDataSourceAttribute("TLS configuration."),
		specBackup:          backupDataSourceAttribute("Backup configuration, limited to the system-bucket opt-in."),
		attrVersion:         dsschema.StringAttribute{Computed: true, MarkdownDescription: "PostgreSQL major version."},
		"users": dsschema.MapNestedAttribute{
			Computed:            true,
			MarkdownDescription: "PostgreSQL users keyed by user name.",
			NestedObject: dsschema.NestedAttributeObject{
				Attributes: map[string]dsschema.Attribute{
					"password":    dsschema.StringAttribute{Computed: true, Sensitive: true, MarkdownDescription: "User password."},
					"replication": dsschema.BoolAttribute{Computed: true, MarkdownDescription: "Whether the user has replication privileges."},
				},
			},
		},
		"databases": dsschema.MapNestedAttribute{
			Computed:            true,
			MarkdownDescription: "Databases keyed by name.",
			NestedObject: dsschema.NestedAttributeObject{
				Attributes: map[string]dsschema.Attribute{
					"extensions": dsschema.ListAttribute{Computed: true, ElementType: types.StringType, MarkdownDescription: "Enabled extensions."},
					"roles":      rolesDS,
				},
			},
		},
		"endpoints": dsschema.SingleNestedAttribute{
			Computed:            true,
			MarkdownDescription: "Connection endpoints.",
			Attributes: map[string]dsschema.Attribute{
				"host":      dsschema.StringAttribute{Computed: true, MarkdownDescription: "Primary (read-write) service host."},
				"read_host": dsschema.StringAttribute{Computed: true, MarkdownDescription: "Replica (read-only) service host."},
				"port":      dsschema.Int64Attribute{Computed: true, MarkdownDescription: "PostgreSQL port."},
			},
		},
	})
	maps.Copy(attributes, statusDataSourceAttributes())

	return dsschema.Schema{
		MarkdownDescription: "Read an existing Cozystack PostgreSQL instance by name and namespace.",
		Attributes:          attributes,
	}
}
